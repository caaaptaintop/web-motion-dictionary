export function actionPrompt(c){
 const {id,scene,reduced:r}=c,v=c.renderVariant??c.variant?.index??0,k=scene?.ui,instant=r||c.values?.duration===0;let t='';
 if(id===46){
  const task=scene?.label||['提交任务','生成任务','文件上传','可计算进度的任务','批量任务'][v];
  if(c.values?.duration===0)return `${task}使用加载指示（Loading indicator），本地处理等待为零时直接进入成功或失败状态，不闪现加载动画；防止重复提交，结果清楚可读。`;
  t=`${task}启动后显示加载指示（Loading indicator），${v===0?`无法估算进度时在按钮内显示${r?'静态忙碌图标与处理中说明':'小型旋转图标'}`:v===1?`使用三个${r?'静态圆点和处理中说明':'依次跳动的圆点'}表示正在生成`:v===2?'显示实际已完成比例的百分比和进度条':v===3?'圆形进度环按真实完成比例填充，并显示百分比':'显示实际已完成数量与总数，并同步显示完成百分比和进度条'}。处理中禁止重复点击，长等待保留说明与取消入口；完成后进入准确的成功或失败状态，失败允许重试。`;
  if(r)t+='减少动态只停止装饰性旋转或跳动，仍保留实际任务等待和进度更新。';
 }else if(id===47){
  const task=scene?.label||'提交',success=k==='payment'?'付款成功':k==='upload'?'上传成功':'已保存';
  t=`${task}完成后显示结果反馈（Success / Error feedback）。`;
  if(scene)t+=`成功时${v===0&&!instant?'让对勾沿路径绘制出来，并':''}让按钮显示对勾与“${success}”；失败时${instant?'直接标明对应错误控件':'让对应输入框或控件短促抖动一次'}，在下方显示具体错误原因与修正方法。`;
  else if(v===0)t+=`成功时${instant?'直接显示完整对勾':'让对勾沿路径绘制出来'}，并显示“已保存”。`;
  else if(v===1)t+='按钮先显示处理中并防止重复提交，处理完成后变为对勾与“已保存”。';
  else if(v===2)t+=`校验失败时${instant?'直接标明错误输入框':'让对应输入框短促左右抖动一次'}，下方显示具体错误原因和修正方法；修正后可重新提交，成功时显示对勾与“已保存”。`;
  else if(v===3)t+='错误字段下方显示具体原因与修正方法，不只靠颜色传达错误；修正后允许重试，成功时显示明确结果。';
  else t+=`操作完成后更新对应内容，${instant?'直接显示准确结果':'高亮一次提示更新位置'}。`;
  t+='处理期间阻止重复提交，反馈不能只靠颜色；减少动态时保留处理等待、错误说明和成功结果，停止装饰性抖动与绘制动画。';
 }else if(id===48){
  const changes=['导航关闭时显示三条横线，打开后变成关闭叉号','内容收起时显示加号，展开后变成减号','暂停时显示播放三角形，播放时变成暂停双线','未收藏时显示空心图标，收藏后内部填充为实心','展开时箭头旋转到展开方向，收起时回到原方向'][v];
  t=`${scene?.label||['菜单按钮','展开按钮','播放按钮','收藏按钮','方向箭头'][v]}使用图标形变（Icon morphing），${changes}。${instant?'两种状态直接切换，不播放图形变换。':v===3?'保持原图标外轮廓稳定，内部填充平滑加深；取消收藏时沿相反过程恢复空心。':'图标在两种状态之间平滑变化，再次点击沿相反过程恢复。'}两种状态共用同一按钮位置和点击区域，键盘可操作，并能读取当前${[0,1,4].includes(v)?'展开':'按下'}状态。`;
 }else if(id===49){
  const action=['筛选后隐藏不符合条件的卡片，其余卡片重新排列','删除一项后，下面的列表向上补位','拖拽卡片时其他卡片自动让出位置，松手后保持新顺序','展开卡片后周围布局调整，收起时恢复','网格在不同列数之间重新排布'][v];
  t=`${scene?.label||'卡片列表'}使用布局过渡（Layout animation），${action}。${instant?'直接呈现最终布局，不播放平移、缩放或淡化。':'卡片从旧位置平滑移动到新位置；存在移除项时先淡出，再让剩余卡片自然补位，容器高度同时平稳调整。'}不要让整个列表闪烁或重新从头入场。${v===2?'保留可见拖动把手及上下移动按钮，键盘也能完成排序。':''}`;
 }else if(id===50){
  const kind=k||['list','profile','music','gallery','title'][v];
  const action=kind==='profile'?'头像连续移动到个人主页顶部':kind==='music'?'小播放器的封面与标题连续放大并移动到完整播放页':kind==='gallery'?'缩略图连续放大为全屏预览':v===4?'列表标题连续移动到详情页标题栏':`${kind==='product'?'主物体图片':'作品卡片主图'}连续放大并移动到详情页顶部，标题跟随到新位置`;
  t=instant?`打开${kind==='profile'?'个人主页':kind==='music'?'完整播放页':kind==='gallery'?'全屏图片预览':'详情页'}时直接显示目标内容，不播放共享元素的大幅位移和缩放；返回时直接恢复原入口。`:`使用共享元素转场（Shared element transition），${action}。返回时沿原路径恢复到原入口，保持同一物体或标题的连续性。`;
  t+=v===4?'标题保持清晰可读。':'图片准备好后才开始转场，等待或失败时保留原入口与可用重试。';
  t+='打开时把焦点移入详情并锁定背景滚动，关闭后恢复原入口焦点与正常滚动。';
 }
 return t;
}
