export function pointerPrompt(c){
 const {id,scene,reduced:r}=c,v=c.renderVariant??c.variant?.index??0,k=scene?.ui,blocked=r||c.runtime?.pointerEnabled===false;let t='';
 if(id===31){
  if(blocked)return '使用系统默认光标，关闭自定义圆点、圆环及跟随提示；图片、视频入口、链接与拖拽替代控件仍可正常操作，输入框保留原生焦点。';
  const full=scene?['portfolio','gallery','brand','hint'].includes(k):v===0;
  t=`${scene?.label||'桌面页面'}使用自定义光标跟随（Cursor follower），${full?'小圆点准确跟随系统光标，外层圆环稍微延迟；进入作品图片时显示“查看”':v===1?'进入图片后在跟随圆环内显示“查看”':v===2?'进入视频区域后显示播放图标':v===3?'进入可拖拽区域后显示“拖动”':'经过链接时改变光标大小和颜色'}。离开对应区域后恢复常态，始终能清楚定位指针；输入框和手机端使用系统默认光标。`;
 }else if(id===32){
  const area=scene?.label||'首屏背景';
  if(blocked)t=v===2?`${area}保留固定的静态背景光区，直接完整显示背景内容与文字，不再用指针蒙版隐藏文字。`:`${area}显示固定的静态${v===3?'边框亮区':'柔和光区'}，不随指针移动。`;
  else t=`${area}使用光标聚光灯（Cursor spotlight），${['柔和圆形亮区跟随光标，经过网格时让局部纹理变清楚','渐变中心随着指针平滑改变位置','光标经过时局部显现背景中的隐藏文字','聚光区域内的卡片边框变亮','一束柔和光线照向指针所在内容'][v]}。`;
  t+=blocked?'正文亮度和位置保持稳定，必要操作保持可用。':'光晕移动保持平滑，不改变正文亮度与位置；手机端显示固定静态光区，文字内容仍可完整阅读。';
 }else if(id===33){
  const target=scene?.label|| (v===1?'多个角色':'角色');
  if(blocked)return `${target}的瞳孔保持静态居中，不跟随指针或自动眨眼；保留清楚完整的角色和必要操作，手机端默认保持静态。`;
  t=`${target}使用鼠标跟随眼睛（Mouse-following eyes），${v===1?'多个角色分别看向同一个光标位置':'两只瞳孔根据光标方向在眼白内部小幅移动'}，始终不能越过眼睛边缘。${v===3?'点击角色时短暂眨眼，再恢复睁眼状态。':''}${v===4?'手机端默认静态，明确启用触摸体验后可短暂看向触摸位置。':'手机端保持静态。'}光标离开页面后瞳孔回到中央。`;
 }else if(id===34){
  if(blocked||c.values?.duration===0)return `${scene?.label||'首屏'}不生成光标拖尾，清除残留轨迹，完整显示内容与必要操作；手机端保持关闭。`;
  t=`在${scene?.label||'首屏'}的空白区域加入克制的光标拖尾（Cursor trail），${['鼠标移动时留下少量圆点，圆点逐渐缩小并淡出','鼠标移动时形成柔和连续线条，随后淡出消失','鼠标移动时依次出现少量小图片，逐渐缩小并淡出','只有快速移动时才留下少量图标残影，随后缩小淡出','少量粒子从光标路径向外散开，逐渐缩小并消失'][v]}。经过正文、按钮和输入框时暂停拖尾，轨迹不能遮挡内容和必要操作，手机端关闭。`;
 }else if(id===35){
  if(blocked)return `${scene?.label||'首屏'}使用静态背景，关闭指针引起的网格、粒子、图片和图层位移；正文和按钮保持稳定且可用，手机端保持同样的静态呈现。`;
  t=`${scene?.label||'首屏'}使用指针响应背景（Pointer-reactive background），${['渐变中心跟随光标缓慢移动','背景网格在光标附近轻微弯曲，远处保持稳定','背景粒子在光标附近轻微避让，远处保持稳定','背景图片按指针方向产生小幅位移','多层图形根据各自与光标的距离产生不同幅度的响应，近处较明显，远处较轻'][v]}。响应带一点延迟，光标停止后缓慢恢复；正文和按钮不能发生位移，手机端使用静态背景。`;
 }
 if(!blocked&&c.values?.duration===0)t=t.replaceAll('稍微延迟','不增加跟随延迟').replaceAll('平滑','即时').replaceAll('缓慢','直接').replace('响应带一点延迟','响应不增加延迟');
 return t;
}
