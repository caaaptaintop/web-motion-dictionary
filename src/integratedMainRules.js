export function rulePrompt(c){
 const {id,scene,reduced:r}=c,v=c.renderVariant??c.variant?.index??0,k=scene?.ui,instant=r||c.values?.duration===0;let t='';
 if(id===51){
  t=`${scene?.label||'路由'}切换使用页面转场（Page transition）。${instant?'直接显示目标页面，不播放大幅位移、色幕或缩放；返回时直接恢复上一页。':[
   '旧页面淡出，新页面淡入；返回时恢复上一页，保持同样克制的淡化。',
   '进入下一层页面时，新页面从右侧轻微滑入并淡入；返回时沿相反方向退出。',
   '返回上一页时沿前进时的相反方向退出，前进时新页面从右侧轻微滑入并淡入。',
   '一块色幕扫过画面，覆盖旧页面后替换内容，再露出新页面。',
   '旧页面先轻微缩小，再进入下一层空间；返回时恢复原页面。'
  ][v]}转场期间保留加载反馈，避免整页长时间空白；快速连续导航以最后一次选择为准。`;
 }else if(id===52){
  const phase=['操作前让用户清楚辨认可点击入口','操作时明确显示按下状态和处理中状态','操作完成后明确显示成功或失败','失败后明确说明怎样修正或重试'][v];
  t=`给所有可操作组件补齐反馈（Feedback），${phase}。悬停、键盘聚焦和按下时提供清楚的状态变化，异步操作保留加载状态并防止重复提交；完成后显示准确的成功或错误结果，并提供可操作的下一步入口。错误说明包含原因与修正方法，不只依赖颜色。${r?'减少动态时停止抖动和装饰性绘制，但保留处理等待及全部状态反馈。':''}`;
 }else if(id===53){
  const target=k||['button','link','drag','expand','input'][v];
  t=`强化组件的操作暗示（Affordance），${({button:'按钮始终拥有清楚边界和明确文字',link:'链接始终保留下划线、颜色或箭头提示',drag:'可拖拽卡片始终显示把手或抓取光标，并提供上移、下移按钮',expand:'可展开项始终带方向箭头、加号或状态文字',input:'输入框始终拥有标签、边框与清楚的键盘焦点样式'})[target]}。`;
  if(target==='button')t+=instant?'按下与松开直接更新选择状态，不播放缩放。':'按下时立即轻微缩小，松开时恢复原尺寸并更新选择状态。';
  else if(target==='drag')t+=instant?'排序后直接呈现新布局。':'拖动或使用移动按钮时，其他卡片平稳让位。';
  else if(target==='expand')t+=instant?'点击后直接展开或收起对应内容。':'点击后平稳展开或收起对应内容，周围布局自然调整。';
  else if(target==='input')t+='提供无需键入的预设内容选择，保留原生焦点与确认结果。';
  else t+='激活后明确显示对应内容与展开状态。';
  t+='动效只用于确认这些已有信号，不要把关键操作隐藏到悬停之后。';
 }else if(id===54){
  const phase=k||['primary','open','keyboard','close','end'][v];
  t=`使用焦点与注意力规则（Focus），${phase==='primary'?'让主操作在视觉上比次要操作更醒目，操作结果清楚可见':phase==='end'?'处理期间显示忙碌状态，完成后显示结果，并把焦点移到明确可用的下一步操作':phase==='keyboard'?'弹窗中的所有操作保留清楚的键盘焦点，Tab与Shift+Tab在弹窗内移动':phase==='close'?'关闭弹窗后把键盘焦点还给实际打开它的原按钮':'弹窗打开时弱化背景，把键盘焦点移动到弹窗中的第一个操作'}。`;
  if(['open','keyboard','close'].includes(phase))t+=`弹窗${instant?'直接打开和关闭，不播放缩放位移':'平稳打开和关闭'}，打开时将注意力和焦点保持在弹窗内，关闭后恢复原按钮焦点与正常滚动。`;
  t+='所有可操作元素都保留清楚可见的键盘聚焦样式。';
 }else if(id===56){
  const kind=k||['hover','expand','sort','pointer','swipe'][v];
  t='完善不同输入方式适配（Input modality support）。';
  if(kind==='hover')t+=`图标短提示在鼠标悬停和键盘聚焦时都可见，手机端点击显示；${instant?'提示直接出现和关闭':'提示轻微展开淡入，离开后平稳关闭'}，不把重要操作藏在提示内。`;
  else if(kind==='expand')t+=`导航入口在桌面端悬停或键盘聚焦时展开，手机端点击展开；指针离开整个菜单后关闭，${instant?'展开与关闭直接切换':'浮层从入口附近展开并轻微淡入，关闭时反向退出'}，保留键盘选择与Escape关闭。`;
  else if(kind==='sort')t+=`卡片可以拖拽排序，同时提供始终可见的上移和下移按钮，键盘用户也能完成相同排序；${instant?'顺序改变后直接呈现新布局':'其他卡片平稳让位，保留新顺序'}。`;
  else if(kind==='pointer')t+=r||c.runtime?.pointerEnabled===false?'关闭装饰性自定义光标跟随，使用系统默认光标和静态内容，主要操作保持可用。':'桌面端小圆点准确跟随指针，外环稍延迟，进入图片显示查看提示；触屏设备关闭装饰性跟随，使用静态内容，输入框使用系统默认光标。';
  else t+=`内容支持左右滑动，同时保留可见的上一项和下一项按钮与当前位置，键盘方向键可切换；${instant?'直接显示目标项，不播放位移':'向前切换时当前项向左离开、下一项从右侧进入，返回时方向相反'}。`;
  t+='所有可操作入口保留清楚的键盘焦点，触屏不依赖悬停才能完成操作。';
 }else if(id===55){
  const kind=k||['parallax','slide','loop','trail','sequence'][v],sub=c.runtime?.submode;
  const which=kind==='parallax'?(sub==='滚动缩放'?'滚动缩放':'视差'):kind==='trail'?(sub==='背景跟随'?'背景跟随':sub==='轻微明暗'?'轻微明暗':'拖尾'):kind==='sequence'?(sub==='自动轮播'?'自动轮播':'图片序列'):kind;
  const normal=({视差:'背景与前景形成克制的视差层次',滚动缩放:'主体随滚动逐步放大',slide:'内容使用长距离进入和离开',loop:'主体使用轻微自动循环或持续旋转，并提供暂停',拖尾:'指针经过空白处时留下少量逐渐消失的拖尾',背景跟随:'背景在指针附近轻微响应，正文与按钮保持稳定',轻微明暗:'使用低强度的明暗变化并提供暂停，不产生强烈闪烁',图片序列:'连续图片帧自动播放并提供暂停和回到首帧入口',自动轮播:'内容自动轮播，用户操作后暂停，同时保留可见前后按钮',feedback:'任务处理中显示加载状态，结束后明确显示成功或错误，并保留重试和取消'})[which];
  const quiet=which==='slide'?'将长距离位移替换为短促淡入淡出，保持内容位置稳定':which==='feedback'?'保留实际加载等待、成功和错误反馈，停止装饰性的旋转或跳动':which==='自动轮播'?'停止自动轮播，保留前后按钮进行手动浏览':which==='图片序列'?'停止自动序列，显示静态首帧并保留回到首帧入口':which==='轻微明暗'?'停止明暗循环，显示稳定亮度的完整内容':`关闭${({视差:'装饰性视差位移',滚动缩放:'滚动缩放',loop:'自动循环与持续旋转',拖尾:'光标拖尾并清除残留轨迹',背景跟随:'背景指针追随'})[which]}，保持主体与内容静态可读`;
  t=`支持减少动态（Reduced motion），检测并响应用户的减少动态偏好。${r?quiet:`${normal}；开启减少动态后，${quiet}`}。保留加载、成功和错误等必要反馈以及可用操作。`;
 }
 return t;
}
