export function interactionPrompt(c){
 const {id,scene,reduced:r}=c,v=c.renderVariant??c.variant?.index??0,k=scene?.ui,staticInput=r||c.runtime?.pointerEnabled===false;let t='';
 if(id===26){
  const target=scene?.label||(v===2?'昼夜照片序列':v===3?'插画角色':'产品展示'),action=['产品随滚动完成一圈平滑旋转','设备外壳随滚动逐步拆开，露出内部结构','一组照片随滚动从白天逐渐变化到夜晚','插画角色随滚动完成一段连续动作','向上滚动时按相反顺序倒放连续产品帧，回到初始姿态'][v];
  t=r?`${target}保留静态主图，关闭随滚动逐帧播放，内容仍可正常浏览。`:`${target}使用图片序列滚动（Image sequence），按滚动进度顺序切换连续帧，${action}。${v===4?'向下滚动时按照正向帧序播放。':'向上滚动时按相反顺序播放，沿原过程复原。'}`;
  t+='图片未加载完成前显示同一主体的静态主图；提前准备连续帧，加载失败时保留静态替代并提供重试，手机端减少帧数。';
 }else if(id===27){
  const target=scene?.label||['全屏章节','横向卡片','图片轮播','手机端功能页','横向卡片'][v];
  t=`${target}使用滚动吸附（Scroll snap），${['每次滚动结束时对齐到一个完整的全屏章节','用户停止滑动后，让最近的卡片对齐到容器中央','停止滑动后对齐完整图片或完整功能项，不停在两项之间','一次显示一个完整步骤，滚动后对齐下一步','只在靠近目标位置时轻微吸附，离目标较远时保留自由滚动'][v]}。`;
  t+=r?'减少动态时直接对齐目标，不播放平滑滚动；':'吸附自然平稳，不突然跳动；';t+='正文页面仍保持自由滚动，不强制把长正文吸附成整屏。';
 }else if(id===28){
  const target=scene?.label||'长文',form=k==='form',directory=!!scene&&['article','tutorial','product','chapter'].includes(k);
  if(form)t='多步骤表单使用进度提示（Progress indicator），按三个步骤的实际当前位置更新顶部进度条，完成时显示完整进度；返回前一步时重新显示该步位置，保留已填写内容。';
  else t=`${target}使用滚动进度提示（Progress indicator），${v===4?'横向时间轴标出当前位置':v===3?'圆环随着阅读进度逐渐填满':v===2?'侧边目录跟随滚动同步高亮当前章节':v===1?'章节编号随阅读位置从1逐步更新到5':`顶部细进度条随着阅读位置${r?'直接更新':'平滑增长'}${directory?'，章节切换时同步高亮侧边目录':''}`}。`;
  t+='指示样式保持细、轻、克制，视觉弱于内容，不遮挡标题和正文。';
 }else if(id===29){
  const target=scene?.label|| (v===2?'主要圆形图标按钮':'主按钮');
  if(staticInput)return `${target}保持静止，关闭磁吸位移和边缘形变，保留普通点击反馈与清楚的键盘焦点；触屏设备使用同样的普通点击方式。`;
  t=`${target}使用磁吸效果（Magnetic button），光标靠近时，${['整个按钮连同文字轻微向光标方向移动','按钮外框和图标保持不动，只有内部文字轻微向光标偏移','圆形图标按钮轻微靠近光标，感应范围扩大','按钮轻微靠近光标，边缘同步产生柔和形变','按钮和文字轻微靠近光标，离开时带少量弹性回到中心'][v]}。${v===4?'回弹逐渐稳定在中心。':'移开后柔和回到原位。'}只应用在少量主要入口，触屏设备保持普通点击反馈。`;
 }else if(id===30){
  const target=scene?.label||'卡片';
  if(staticInput)return `${target}保持正面静止，关闭指针倾斜、高光追随与悬停抬升；保留清晰文字和必要操作，手机端默认使用静态呈现。`;
  t=`${target}使用轻微立体倾斜（Tilt card），${['根据光标位置向四周对应方向小幅旋转','卡片随光标轻微倾斜，表面高光同步移动','图片与文字产生轻微前后分层，卡片随光标倾斜时呈现层次','悬停时卡片抬起并增加透视，随光标方向轻微倾斜','随光标轻微倾斜，光标离开后平稳回到正面'][v]}${scene&&v!==1?'，表面高光同步移动':''}。文字层保持清晰，${v===4?'回正后准确停稳':'光标移开后平稳回正'}，手机端关闭倾斜。`;
 }
 if(!staticInput&&[29,30].includes(id)&&c.values?.duration===0)t=t.replaceAll('柔和回到','直接回到').replaceAll('平稳回到','直接回到').replaceAll('平稳回正','直接回正').replace('带少量弹性回到中心','直接回到中心').replace('回弹逐渐稳定在中心','不播放回弹，直接稳定在中心');
 return t;
}
