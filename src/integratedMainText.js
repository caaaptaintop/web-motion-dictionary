export function textPrompt(c){
 const {id,scene,reduced:r}=c,k=scene?.ui,v=c.renderVariant??c.variant?.index??0,D=c.values?.duration;let t='';
 if(id===16){
  const target=({short:'简短标题',slogan:'口号',data:'数据结论',sentence:'重点句'})[k]||'标题';
  if(r)return `${target}按完整语义直接显示，保持句子顺序和清晰阅读，不播放逐词动画。`;
  if(D===0)return `启动延迟结束后，${target}${v===1?'先直接显示关键词，再补齐其他词组':'按词组的阅读顺序依次直接显示'}；保留原句排列，各词在对应的启动时刻直接到达最终状态，不播放单词的渐变、模糊或位移。`;
  t=`${target}使用按词显现（Word reveal），按照中文语义拆成短语，${['每个词依次淡入','先显示关键词，再补齐其他词组，最终句子顺序不变','每个词从下方轻微进入','词组从模糊逐渐变清晰'][v]}。关键词可以稍微强调，整句连贯完成，不能影响阅读。`;
 }else if(id===17){
  const target=({english:'很短的英文单词',logo:'Logo文字',number:'数字文字',chinese:'主标题中的四个关键词'})[k]||'简短标题';
  if(r)return `${target}直接完整显示，不播放逐字符动画；其他文字保持整行显示，保证完整文意与阅读顺序。`;
  if(D===0)return `${v===4?'鼠标经过或键盘聚焦时，':''}启动延迟结束后，${target}的字符按阅读顺序依次直接显示；每个字符在对应的启动时刻直接到达最终状态，不播放淡入、落下、旋转或模糊过渡。其他文字保持整行显示。`;
  t=`${target}使用按字符显现（Character reveal），${['字符依次淡入并轻微上移','字符从不同高度落入后归位','字符轻微旋转后归位','字符从模糊逐渐恢复清晰','鼠标经过或键盘聚焦时字符依次响应'][v]}。其他文字保持整行出现，动画连贯完成，不把长正文拆成逐字播放。`;
 }else if(id===18){
  const loop=v===3&&(!scene||k==='short')&&!r&&D!==0;
  const subject=k==='terminal'||!scene&&v===0?'一条短命令':k==='search'||!scene&&v===2?'搜索框中的输入内容':k==='chat'?'聊天回复':k==='ai'||!scene&&v===1?'AI回答':loop?'多个短句':v===3?'第一条短句':'简短标题';
  if(r||D===0)t=`${r?'':'启动延迟结束后，'}直接完整显示${subject}，不进行逐字输入、删除或自动循环。文字完成后保持可见，其他正文和操作入口稳定可用。`;
  else t=loop?'使用打字机效果（Typewriter）轮流输入多个短句；每句逐字输入完成后短暂停留，再逐字删除，随后切换下一句继续循环。':'使用打字机效果（Typewriter）逐字输入'+subject+'。文字完成后立即保持可见，不循环删除重打。';
  if(!(scene&&k==='search'))t+=r?'光标保持静态，不持续闪烁。':'显示闪烁光标，输入完成后光标仍可见并继续闪烁。';
  t+='正文介绍不使用逐字等待，保留实际内容和必要操作。';
 }else if(id===19){
  const number=k==='data'||v===1,status=k==='status'||v===4,hover=k==='easter'||v===2;
  const target=number?'目标数值':status?'完成状态':k==='game'?'游戏界面的重点英文标题':'英文标题';
  if(r||D===0)return `${hover?'鼠标悬停或键盘聚焦时，':r?'':'启动延迟结束后，'}直接显示准确的${target}，不播放随机字符或数字跳动。中文正文保持稳定清晰，保留必要的触发和操作。`;
  t=number?'让数字快速跳动后收敛到实际数据的准确目标值。':status?'让系统状态从Processing经过短暂的乱码解码（Scramble text）变为Complete。':hover?'鼠标悬停或键盘聚焦时，让英文文字短暂出现随机字符，再迅速恢复为准确文字。':v===3?'页面进入时，让重点英文关键词从短暂随机字符迅速解码为正确内容。':`让${target}使用乱码解码（Scramble text）：先出现短暂的随机字符，再迅速收敛为正确文字。`;
  t+=hover?'每次明确触发只播放一次，完成后保持，不能自行反复播放。':'每次触发只播放一次，完成后保持准确结果。';t+='中文正文保持稳定。';
 }else if(id===20){
  const loop=v===3&&!r,svg=v===4;
  const target=svg?'两个SVG字形':v===0?'两个职业名称':v===1?'Loading与Ready状态':v===2?'数字与单位':'同一位置的三个短词';
  if(r)return svg?'直接显示目标SVG字形，不播放轮廓变形。保持文字可辨认与操作可用。':`${target}直接显示对应状态，不播放自动循环、模糊或交叉淡化；保留${scene?'可见的手动切换操作':'完整可读的文字'}。`;
  if(svg&&D===0)return '切换延迟结束后直接显示目标SVG字形，不播放轮廓变形；保持字形准确、可辨认。';
  if(svg)return '使用文字变形（Text morphing），让一个SVG字形的轮廓连续变化为另一个字形，最终准确到达目标形状。保持字形可辨认，不以直接替换文字代替连续形变。';
  t=v===0?'让一个职业名称平滑替换为另一个职业名称。':v===1?'让产品状态从Loading平滑变化为Ready。':v===2?'让数字和单位平滑更新，保持同一实际数量及其准确表达。':'让标题中同一位置的三个短词使用文字变形（Text morphing）依次循环替换。';
  if(D===0)t=t.replaceAll('平滑','直接');
  t+=D===0?'切换时直接替换文字与对应容器宽度，不播放模糊或淡化。':'切换时使用轻微模糊和交叉淡化，旧词淡出的同时新词淡入，容器宽度平滑过渡。';
  t+=loop?'用户悬停后暂停循环，并提供明确的暂停与继续操作。':scene?'通过可见操作触发单次更新，不自动反复切回初态。':'启动延迟结束后执行一次更新，完成后保持目标状态，不自动循环。';
 }
 return t;
}
