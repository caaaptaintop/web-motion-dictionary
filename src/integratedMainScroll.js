export function scrollPrompt(c){
 const {id,scene,reduced:r}=c,v=c.renderVariant??c.variant?.index??0,k=scene?.ui;let t='';
 if(id===21){
  const context=scene?`${scene.label}的首屏`:'首屏';
  if(r)return `${context}保持静态层次，关闭装饰性视差位移；正文与标题随页面正常滚动，保留完整图片、清晰内容和可用操作。`;
  t=v===0?`${context}使用轻微视差滚动（Parallax scrolling），背景移动最慢，中间装饰稍快，前景标题与正文保持正常滚动。`:v===1?`${context}使用视差滚动，前景装饰移动较快，背景移动较慢，形成前后深度。`:v===2?`${context}的图片内部景物随滚动轻微移动，图片外框和文字保持不变。`:v===3?`${context}使用视差滚动，让前景与背景沿相反方向移动，形成清楚的空间感。`:`${context}随鼠标位置产生小范围视差，不依赖页面滚动；指针离开后回到中性位置。`;
  t+='层次清楚而克制，手机端减弱位移，不能影响正文阅读和必要操作。';
 }else if(id===22){
  const layers=scene?`${scene.label}的首屏拆成背景、中景主体与前景文字三层`:['将天空、山体、人物与前景植物分层','将背景网格、中间产品与前景文字分层','将多张透明图片及前景内容叠成具有景深的完整场景','将背景、中景主体与前景内容分层'][v];
  t=r?`${layers}，保持静态构图，不播放装饰性层间位移；内容仍可正常滚动浏览。`:`${layers}，使用多层视差（Multi-layer parallax）。滚动时各层保持不同的移动速度，${v===3?'同时沿横向与纵向产生轻微位移，':''}背景变化最轻，前景更明显。`;
  t+='各层始终对齐成一个完整画面，不要漂散；保持主体和文字清楚可辨。';
 }else if(id===23){
  const kind=k||['portfolio','features','timeline','gallery','gallery'][v],noun=({portfolio:'作品卡片',story:'品牌故事章节',features:'产品功能章节',timeline:'时间轴节点',gallery:'画廊图片'})[kind];
  if(r||c.runtime?.horizontal===false)return `将四个${noun}按原顺序排列为普通纵向列表，随正常页面滚动浏览，不把向下滚动转换为横向位移。保留完整内容与各项操作，进入和离开该区域时自然衔接。`;
  t=`这一段使用横向滚动（Horizontal scroll），用户继续向下滚动时，${kind==='timeline'?'横向时间轴沿节点顺序向右推进，四个节点从右向左依次经过视口':`四个${noun}保持一行，从右向左依次经过视口`}。进入和离开横向区域时保持自然衔接，手机端恢复为普通纵向列表。`;
 }else if(id===24){
  const map=k==='map'||!scene&&v===2,target=k==='3d'?'3D产品主体':k==='product'||!scene&&v===1?'产品图片':k==='chapter'?'章节主图':'照片';
  if(r)return `${map?'地图保持全局视图':`${target}保持完整的静态尺寸`}，关闭滚动缩放；标题保持清晰稳定，继续滚动后自然进入详情内容。`;
  t=map?'滚动进入地图章节时使用滚动缩放（Scroll zoom），地图从全局逐渐缩放到城市，缩放进度跟随滚动；地名和标记保持清晰可读。':`滚动进入${k==='chapter'?'新章节':'展示章节'}时使用滚动缩放（Scroll zoom），${target}从画面中央的小尺寸逐渐放大到接近全屏，缩放进度跟随滚动。`;
  if(!map&&!scene&&v===1)t='滚动进入产品章节时使用滚动缩放（Scroll zoom），产品从远处逐渐靠近镜头，主体在画面中央逐步放大，推进进度跟随滚动。';
  if(!map&&!scene&&v===3)t='照片使用滚动缩放（Scroll zoom），随滚动逐渐放大，继续深入后自然进入照片内部对应的下一段内容。';
  if(!map&&!scene&&v===4)t='滚回上方时，已放大的照片沿原路径逐渐缩小，缩小进度跟随反向滚动；向下滚动时沿同一路径放大。';
  t+='标题保持清晰稳定，不跟随主体放大；继续滚动后自然进入详情内容，滚回上方时沿原路径缩小。';
 }else if(id===25){
  const kind=k||['features','product','map','longform','brand'][v];
  const action=kind==='product'?'产品暂时固定在中央，三个章节随滚动依次高亮，对应零件逐个展开':kind==='map'?'地图的取景与比例保持固定，三个章节随滚动依次高亮，对应地点与路线持续更新':kind==='longform'?'长图展示区域暂时固定，旁边三段解释随滚动依次推进并高亮，图内内容与当前解释对应':v===4?'背景保持固定，三个前景章节随滚动依次覆盖或离开':kind==='features'||kind==='tutorial'?'右侧界面暂时固定，左侧三个说明步骤随滚动依次进入并高亮；每换一段，右侧只更新对应区域':kind==='data'?'右侧数据展示暂时固定，左侧三个说明章节随滚动依次高亮，数据与图表同步更新':'右侧内容展示暂时固定，左侧三个说明章节随滚动依次高亮，右侧同步显示对应章节内容';
  t=`${scene?.label||'章节内容'}使用固定式滚动叙事（Sticky scrollytelling），${action}。`;
  if(r)t=t.replace('对应零件逐个展开','对应零件直接切换到该章节状态').replace('图内内容与当前解释对应','图内保持静态画面，与文字说明共同呈现')+'减少动态时不播放连续拆解或图像平移，保留章节高亮和必要内容切换。';
  t+='最后一段结束后恢复正常滚动，反向滚动时保持章节与展示内容对应。';
 }
 return t;
}
