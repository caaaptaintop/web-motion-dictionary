export function surfacePrompt(c){
 const {id,scene,reduced:r}=c,v=c.renderVariant??c.variant?.index??0,k=scene?.ui,instant=r||c.values?.duration===0;let t='';
 if(id===36){
  const target=scene?.label|| (v===1?'3D角色头部':'产品模型');
  if(r)return `${target}保持正面静态展示，关闭指针旋转、视角移动、光照追随和自动旋转；加载前显示同一主体的静态图，保留必要内容与操作。`;
  t=`首屏${target}使用3D物体跟随（3D object follow），${['光标移动时模型朝光标方向小幅旋转，保持主体正面可见','只有角色头部跟随指针小幅转动，保持面部可见','相机根据光标位置绕物体小幅移动，模型主体保持稳定可见','模型灯光方向随指针变化，物体几何姿态保持不变','模型随光标小幅转动，离开后缓慢回到正面'][v]}。${v===4?'回正后准确停稳。':v===2?'光标离开后视角回到初始位置。':v===3?'光标离开后恢复中性光照。':'光标离开后缓慢回正。'}加载前显示同一主体的静态图，手机端改为轻微${v===2?'自动视角移动':v===3?'自动光照变化':'自动旋转'}，并提供暂停。`;
 }else if(id===37){
  const noun=scene?.label||['问答列表','设置面板','侧边栏目录','补充详情','折叠列表'][v],content=({faq:'答案',settings:'更多设置选项',directory:'二级目录',detail:'补充内容',list:'对应详情'})[k]||['答案','更多设置选项','二级目录','补充内容','对应内容'][v];
  t=`${noun}使用折叠展开（Accordion），点击标题后，${content}${instant?'直接显示':'从标题下方向下展开，下面的内容平稳下移'}；再次点击${instant?'直接收起':'按原路径收起'}。展开项保持高亮，加号同步变成减号，收起后标题仍清楚可见。`;
 }else if(id===38){
  const kind=k||['account','nav','select','tooltip','actions','select'][v];
  const action=kind==='nav'?'鼠标悬停或键盘聚焦导航入口时，展开多列菜单；指针移出整个入口与菜单区域后关闭':kind==='tooltip'?'悬停或键盘聚焦图标时，在旁边显示简短说明（Tooltip），离开后关闭；提示中不放需要操作的按钮':kind==='account'?'点击头像后展开账号菜单':kind==='select'?'点击选择框后打开选项列表，选中后更新选择值':kind==='filter'?'点击筛选入口后打开可操作的筛选浮层（Popover）':'点击按钮后打开带操作项的小浮层（Popover）';
  t=`${action}。${instant?'浮层直接出现和关闭，不播放位移或淡化。':`浮层从触发入口附近${v===5?'向上':'向下'}展开并轻微淡入，关闭时平稳退出。`}浮层与入口保持邻近，${v===5?'上方也不足时选择可容纳的位置':'下方空间不足时改为向上展开'}。普通图标说明使用短提示，带操作按钮的内容使用Popover，手机端改为点击展开；保留可见焦点和键盘选择、关闭操作。`;
 }else if(id===39){
  const noun=scene?.label||['确认操作','登录','图片预览','重要警告','手机端内容'][v];
  t=instant?`打开${noun}弹窗（Modal）时直接显示遮罩与弹窗内容，关闭时直接退出。`:`打开${noun}弹窗（Modal）时，背景遮罩先轻微变暗，${['弹窗随后在画面中央淡入并小幅放大','登录弹窗从触发按钮附近出现并扩展到中央','图片从缩略图扩展到中央预览弹窗','警告弹窗快速出现，随后保持稳定','手机端弹窗从底部进入'][v]}；关闭时按相反顺序和原路径退出。`;
  if(k==='confirm'||!scene&&v===0)t='点击“删除”后'+t;
  t+='弹窗打开期间锁定背景滚动，把键盘焦点放进弹窗并限制在弹窗内部；保留明确关闭入口与Escape关闭，关闭后将焦点还给实际触发控件。';
 }else if(id===40){
  const kind=k||['cart','nav','filter','mobile','mobile'][v],noun=({cart:'购物车',nav:'手机导航',filter:'筛选条件',detail:'详情面板',mobile:'分享选项'})[kind],side=v===1?'左侧':v===3||v===4?'底部':'右侧';
  t=instant?`点击入口后直接打开${noun}抽屉（Drawer）和背景遮罩，不播放滑入滑出。`:`点击入口后打开${noun}抽屉（Drawer），面板从${side}${side==='底部'?'升起':'滑入'}，背景同时出现轻微遮罩；关闭时向${side}退回。`;
  t+=instant?(v===1?'手机端显示接近全屏的左侧导航，保留明确关闭入口。':'手机端显示接近全屏的底部面板，支持向下拖动关闭，同时保留明确关闭入口。'):v===4?'底部面板支持向下拖动关闭，同时保留可点击和键盘使用的关闭按钮。':v===1?'手机端导航仍从左侧打开并向左退回，面板接近全屏，保留明确关闭入口。':'手机端改为接近全屏的底部面板，从下方升起，并支持向下滑动关闭，同时保留明确关闭入口。';
  t+='打开时锁定背景滚动，键盘焦点进入面板，关闭后恢复触发控件焦点与正常滚动。';
 }
 if(!r&&c.values?.duration===0&&id===36)t=t.replaceAll('缓慢','直接');
 return t;
}
