export function feedbackPrompt(c){
 const {id,scene,reduced:r}=c,v=c.renderVariant??c.variant?.index??0,k=scene?.ui,instant=r||c.values?.duration===0;let t='';
 if(id===41){
  t=`${scene?.label||'标签页'}切换使用平滑过渡（Tab transition）。${instant?'点击新标签后直接更新选中指示器与对应内容，不播放滑动或交叉淡化。':`点击新标签后，${v===1?'胶囊背景':'下划线指示器'}先滑到对应位置，${v===4?'等待目标数据加载完成后再让内容交叉淡化':v===3?'新内容按前后标签对应的左右方向滑入，旧内容同时淡出':'内容区域再交叉淡化'}。`}${v===4&&instant?'目标数据准备好后才替换原内容，等待期间保留加载反馈。':''}`;
  t+=instant?'容器按真实内容尺寸调整，保持完整可读。':'容器高度平稳调整，避免下面的页面突然跳动。';t+='快速切换以最后选择为准，保留键盘切换与清楚的选中状态。';
 }else if(id===42){
  const auto=scene?k==='case':v===4;
  t=`${scene?.label||'内容'}使用轮播切换（Carousel）。${instant?'通过可见前后按钮、方向键或横向拖拽切换，直接显示目标项，不播放平移、缩放或淡化。':v===1?'切换时旧图片与新图片同时交叉淡化，保留稳定的内容位置。':v===2?'中央卡片放大突出，两侧卡片缩小；切换时当前卡片离开，新卡片移动到中央。':v===3?'拖拽松手后自然吸附到距离最近的一张，未超过中心阈值时回到当前项。':'点击下一张或向左拖拽时，当前卡片向左离开，下一张从右侧进入并吸附到中央；上一张按相反方向切换。'}`;
  t+='始终显示当前位置，并保留可见前后按钮与键盘操作；目标图片准备好后才开始切换，等待时保留当前完整内容。';
  t+=auto?(r?'减少动态时停止自动播放，保留手动切换。':'自动播放时提供暂停入口；用户点击、拖拽或键盘操作后暂停自动播放，不能自行重新开启。'):'由用户主动切换，不增加自动播放。';
 }else if(id===43){
  const kind=k|| (v===0?'copy':'save'),error=v===4&&kind!=='network';
  const trigger=error?'保存失败后显示可处理的错误提示':kind==='copy'?'实际复制链接成功后显示“已复制”，复制失败时显示可重试的失败提示':kind==='cart'?'加入购物车成功后显示加购结果':kind==='network'?'网络断开时显示连接中断提示，恢复连接后显示恢复结果':kind==='notice'?'出现无需立刻回答的信息时显示简短提醒':'保存成功后显示保存结果';
  t=`${trigger}，使用轻提示（Toast）。${instant?'提示直接出现与关闭，不播放位移或淡化。':v===1?'提示在页面角落淡入，关闭时淡出。':'提示从页面底部轻微上移并淡入，关闭时淡出。'}`;
  t+=v===2?'不同消息依次堆叠，最多保留三条，避免遮挡正文和操作。':'连续操作更新同一条提示，不让重复消息遮住页面。';
  t+=error||kind==='network'?'错误或断线提示持续保留，等待用户处理或关闭；问题恢复后更新结果。':'普通提示完全进入后保留足够阅读时间，再退出。';
  if(v===3)t+='提示提供撤销按钮，点击后实际撤销刚完成的保存，并关闭该条提示。';
  t+='保留手动关闭；失败不能显示成功结果。';
 }else if(id===44){
  const target=Number(c.values?.target??1280),unit=v===3?'%':k==='mileage'?'千米':k==='sales'||!scene&&v===4?'元':'';
  const subject=scene?.label||'数据卡片';
  t=`${subject}进入视口后播放数字计数（Animated counter），${instant?`直接显示准确目标${target}${unit}，不播放逐帧计数或数字翻动`:`${v===0||v===2||v===3?'从零':'从更新前的数值'}平滑更新到准确目标${target}${unit}` }。`;
  if(!instant&&v===2)t+='每一位数字使用上下翻动的方式变化，分隔符保持原位。';
  if(v===3)t+=`百分比与进度条同步${instant?'更新':'变化'}，两者最终一致。`;
  if(v===4)t+='金额变化时标出实际增减方向，没有变化时准确保留原值。';
  t+='每次进入后的有效触发只播放一次，千位分隔符和单位始终保持稳定；改目标或重播时取消旧动画，从有效起点更新，结束后保持准确结果。';
 }else if(id===45){
  const layout=scene?.label||['卡片标题与正文','固定比例图片','多行列表','内容布局','内容布局'][v];
  t=`${layout}加载时显示骨架屏（Skeleton loading），${v===0?'标题和正文用灰色条占位':v===1?'图片位置用固定比例的色块占位':v===2?'列表先显示多行相同结构的骨架':'骨架块保持与真实内容相同的尺寸和布局'}。`;
  t+=r?'骨架保持静态，不播放呼吸或高光，保留实际加载等待。':v===3?'占位块使用轻微、缓慢的明暗呼吸。':v===4?'一道柔和高光从骨架表面经过。':'占位结构保持静态，不叠加呼吸或扫光。';
  t+=`数据到达后${r?'直接':'平滑'}替换为真实内容，骨架与内容的尺寸、布局始终一致，页面位置不能跳动；短暂等待时避免闪现骨架。`;
 }
 return t;
}
