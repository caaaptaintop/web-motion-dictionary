export function revealPrompt(c){
 const {id,scene,reduced:r}=c,k=scene?.ui,v=c.renderVariant??c.variant?.index??0;let t='';
 if(id===11){
  const target=k==='brand'?'品牌首屏标题':k==='hero'?'重点标题':k==='portfolio'?'作品集图片':k==='chapter'?'章节封面图片':'主视觉图片';
  t=r?`${target}直接完整显示，不播放裁剪揭示。`:`${target}使用裁剪揭示（Clip-path reveal），${['从左向右平滑展开','从下向上逐渐露出','从中央向两侧打开','通过圆形可见区域向外扩张','让多边形裁剪区域逐渐变为完整矩形'][v]}。`;
  t+=r?'主体位置和尺寸保持稳定，不叠加旋转和缩放。':'主体本身的位置和尺寸保持稳定，只改变可见区域；效果干净，不叠加旋转和夸张缩放。';
 }else if(id===12){
  const target=k==='brand'||!scene&&v===1?'重点文字':k==='gallery'?'摄影主图':k==='portfolio'?'作品集主图':k==='poster'?'海报主图':'主视觉图片';
  t=r?`${target}直接完整显示，移除装饰性蒙版，不播放遮罩变化。`:`${target}使用蒙版显现（Mask reveal），${['渐变蒙版从一侧扫过','让光线扫过后露出文字','通过墨迹或不规则笔刷形状揭示图片','让噪点遮挡逐渐消散','通过柔边圆形区域从中央向外扩散'][v]}。`;
  t+=r?'主体位置保持稳定，内容完整可读。':'边缘保持自然，不出现生硬矩形；只处理指定的重点视觉区域，主体位置保持稳定。';
 }else if(id===13){
  const target=({pages:'页面',portfolio:'作品集项目',carousel:'大图轮播',chapter:'品牌章节',video:'叙事画面'})[k]||'内容';
  if(r)return `切换${target}时直接显示已准备好的目标内容，不播放色幕、大幅位移或缩放；保留快速导航、跳过和返回操作，以最后选择为准。`;
  t=`${target}切换时使用擦除转场（Wipe transition），${['一个纯色遮罩从左向右扫过','一个纯色遮罩从上向下覆盖','两个纯色色块从两侧向中央合拢','一个纯色遮罩沿对角线扫过','一个纯色圆形区域向外扩张覆盖整个画面'][v]}。完全覆盖旧内容后才替换为已准备好的新内容，再让遮罩退出并露出新内容。动作清楚、节奏利落，用户快速导航时允许跳过，新的选择取消未完成的旧转场。`;
 }else if(id===14){
  const target=({hero:'主标题',chapter:'章节标题',slogan:'宣传语',feature:'少量重点文字'})[k]||'主标题';
  if(r)return `${target}和正文直接完整显示，保留原有文字、标点和阅读顺序，不播放逐项延迟、裁剪、模糊或位移。`;
  t=`${target}使用文字显现（Text reveal），${['按照每一行分别处理，文字从自己的裁剪容器中向上显现，并带轻微淡入','按照语义词组依次显现，保持阅读顺序','简短文字按照字符顺序依次显现，保留完整文意与标点','让文字从各自裁剪窗口中向上显现，并带轻微淡入','让文字从轻微模糊逐渐变清晰，并淡入显示'][v]}。正文只使用普通淡入，不对正文逐词或逐字播放。`;
 }else if(id===15){
  const target=({hero:'多行大标题',quote:'引言',chapter:'章节标题',brand:'品牌文案'})[k]||'多行标题';
  if(r)return `${target}按照完整行结构直接显示，不播放逐行位移、模糊或交错淡入；保持句子完整与清楚的阅读顺序，不拆成单个字符。`;
  t=`${target}使用按行显现（Line reveal），${['每行从下方轻微进入，按照阅读顺序依次出现','每行从自己的裁剪窗口中向上升起，按照阅读顺序依次出现','当前一行清晰并完成后，再让下一行显现','各行按照阅读顺序轻微交错淡入'][v]}。保持句子完整，不要拆成单个字符。`;
 }
 return t;
}
